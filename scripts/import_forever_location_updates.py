#!/usr/bin/env python3
"""Fill only missing catalog phases using the newer, pinned corrected Forever source."""
import argparse
import json
from pathlib import Path
import subprocess
import tempfile
from import_forever_locations import Catalog, ROOT, lua, quest_name

REF = 'c6745129ef9ea5e6dd1cdcd77224090f71bda880'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('questiedb', type=Path)
    args = parser.parse_args()
    source = args.questiedb.resolve()
    revision = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=source, text=True).strip()
    if revision != REF:
        raise SystemExit('Use QuestieDB ' + REF)
    with tempfile.TemporaryDirectory() as directory:
        output = Path(directory) / 'facts.json'
        subprocess.run([str(source / 'tools/lua-binary/linux-x64/lua'),
                        str(ROOT / 'scripts/export_forever_locations.lua'), str(ROOT), str(output)],
                       cwd=source, check=True)
        data = json.loads(output.read_text())
    catalog = Catalog(data, source, {}, {})
    updates, maps = {}, {}
    for quest_id, missing in data['missingLocations'].items():
        record = catalog.record(int(quest_id))
        if quest_name(record.get('name', '')).casefold() != quest_name(missing.get('name', '')).casefold():
            continue
        for role in ('pickup', 'objective', 'turnin'):
            if missing.get(role) and record.get(role):
                points = record[role]
                for point in points:
                    point['source'] = 'QuestieDB ' + REF[:8]
                    maps[point['mapId']] = catalog.names[point['mapId']]
                updates.setdefault(int(quest_id), {})[role] = points
    lines = ['-- Generated by scripts/import_forever_location_updates.py.',
             '-- Corrected Forever QuestieDB ' + REF + '; fill missing phases only.',
             'local _,ns=...', 'local updates={']
    for quest_id, record in sorted(updates.items()):
        lines.append(f'    [{quest_id}]={lua(record)},')
    lines += ['}', 'for id,roles in pairs(updates) do',
              '    local record=ns.foreverQuestLocations[id]',
              '    if record then for role,points in pairs(roles) do',
              '        if not record[role] or #record[role]==0 then record[role]=points end',
              '    end end', 'end']
    for map_id, name in sorted(maps.items()):
        lines.append(f'ns.foreverLocationMaps[{map_id}]={lua(name)}')
    (ROOT / 'clients/forever/guides/ForeverQuestLocationUpdates.lua').write_text('\n'.join(lines) + '\n')
    print(f'Filled {sum(len(v) for v in updates.values())} missing phases across {len(updates)} quest IDs')

if __name__ == '__main__':
    main()
