-- Reproducible all-guide scope audit. Optional Markdown output argument.
local output=arg[1];arg[1]=nil
local audit=dofile('scripts/audit_quest_locations.lua')
local ns,guides=audit.ns,audit.guides
local lines={'# All-guide routing and data audit','','Generated by `scripts/audit_all_guides.lua`. Counts are the union of race/class variants in each guide; shared quests may appear more than once.','','| Guide | Quest steps | With minimum level | With chain rules | With destination or authored travel |','| --- | ---: | ---: | ---: | ---: |'}
local guideCount,stepCount,levelCount,chainCount,travelCount=0,0,0,0,0
for _,guide in ipairs(guides:List()) do
    if guide.id~='first-steps' then
        local races,classes={HUMAN=true,ORC=true},{HUNTER=true}
        for _,step in ipairs(guide.steps) do
            for _,race in ipairs(step.races or {}) do races[race]=true end
            if step.class then classes[step.class]=true end
        end
        local seen,n,l,c,t={},0,0,0,0
        for race in pairs(races) do for class in pairs(classes) do
            UnitRace=function() return race,race end;UnitClass=function() return class,class end
            for _,step in ipairs(guides:GetSteps(guide.id)) do
                if step.questId and not seen[step.id] then
                    seen[step.id]=true;n=n+1
                    if step.minLevel then l=l+1 end
                    if #(step.requires or {})+#(step.requiresAny or {})>0 then c=c+1 end
                    if step.travel or step.mapId and step.x and step.y then t=t+1 end
                end
            end
        end end
        guideCount=guideCount+1;stepCount=stepCount+n;levelCount=levelCount+l;chainCount=chainCount+c;travelCount=travelCount+t
        lines[#lines+1]=string.format('| %s | %d | %d | %d | %d |',guide.id,n,l,c,t)
    end
end
lines[#lines+1]=''
lines[#lines+1]=string.format('Total: **%d leveling guides**, %d quest steps, %d steps with minimum levels, %d with chain rules, %d with a destination or authored travel.',guideCount,stepCount,levelCount,chainCount,travelCount)
lines[#lines+1]=''
lines[#lines+1]='Hub grouping, prerequisite recovery, source destinations, search and event coalescing use shared code for all guides. Destination pins are not pathfinding: only explicitly authored travel legs describe transports/entrances. In-game availability remains authoritative.'
lines[#lines+1]=''
lines[#lines+1]='See `QUEST_LOCATION_COVERAGE.md` for every unresolved coordinate and `QUEST_LOCATION_SOURCES.md` for source provenance. Missing prerequisite metadata does not establish that a quest has no prerequisites. Authored rules take precedence; unsupported negative prerequisite IDs and combined group/single rules are not imported.'
if output then local f=assert(io.open(output,'w'));f:write(table.concat(lines,'\n')..'\n');f:close() end
print(lines[#lines-4])
return {ns=ns,guides=guides,guideCount=guideCount}
