for _, zone in ipairs(zones) do
    local guide = {
        id = "horde-" .. zone.name:lower():gsub("[^%w]+", "-"):gsub("%-$", ""),
        title = "Horde: " .. zone.name, zone = zone.name,
        continent = "Kalimdor", faction = "Horde",
        levelMin = zone.low, levelMax = zone.high,
        levelRangeEstimate = zone.levelEstimate == true,
        description = "Quest-by-quest source catalog for " .. zone.name ..
            ". Confirm availability and objective locations in your Forever quest log.",
        contentStatus = "source-backed test route; in-game verification pending",
        testingOnly = true, limitedData = #zone.entries < 10, steps = {},
    }
    local candidateIDs = {}
    local included = {}
    for _, row in ipairs(zone.entries) do included[row[1]] = true end
    for _, row in ipairs(zone.entries) do
        local id, title, lvl, x, y, prereq = row[1], row[2], row[3], row[4], row[5], row[6]
        candidateIDs[#candidateIDs+1] = id
        local required = prereq and included[prereq] and {prereq} or nil
        local baseID = "att-horde-kal-" .. id
        guide.steps[#guide.steps+1] = {
            id = baseID .. "-accept", questId = id, action = "accept",
            title = "Pick up: " .. title, zone = zone.name, level = lvl or zone.low,
            x = x, y = y, requires = required,
            text = "Accept " .. title .. " if your character is eligible. Check the quest giver and prerequisites in-game.",
            sourceStatus = "ATT Forever quest catalog; verify live client",
        }
        guide.steps[#guide.steps+1] = {
            id = baseID .. "-turnin", questId = id, action = "turnin",
            title = "Complete: " .. title, zone = zone.name, level = lvl or zone.low,
            requires = required,
            text = "Finish and turn in " .. title .. ". Follow the live quest log for objectives and the turn-in location.",
            sourceStatus = "ATT Forever quest catalog; verify live client",
        }
    end
    ns.starterGuides[#ns.starterGuides+1] = guide
    ns.foreverQuestCatalog["Horde:" .. zone.name] = candidateIDs
end
